/* =========================================================================
 * sl_rhi_vk_shaders.h —— Vulkan SPIR-V 着色器字节码（固化进源码）
 *
 * 九组 SPIR-V 由下方注释中的 VKSL 源码（GLSL 450）经 glslang 16.6.0
 * 一次性编译生成（glslang -V --target-env vulkan1.0），以 C 数组固化
 * 进后端源码 —— 构建与运行均零 Vulkan SDK / 编译工具依赖。
 *
 * 六组程序槽位与 GL/D3D11 后端逐组对应：
 *   VS_SCENE  + FS_FLAT  -> SLR_PROG_FLAT（v1 MVP/Color + 可选纹理）
 *   VS_SCENE  + FS_TEX   -> SLR_PROG_TEX
 *   VS_PSCENE + FS_PFLAT -> SLR_PROG_PFLAT（PerDraw UBO + push constant）
 *   VS_PSCENE + FS_PTEX  -> SLR_PROG_PTEX
 *   VS_FULL   + FS_BLIT  -> SLR_PROG_BLIT
 *   VS_FULL   + FS_POST  -> SLR_PROG_POST
 *
 * 与 GL 后端的语义差异全部在着色器内消化，保证同像素：
 *   1) NDC y 翻转：每个 VS 末尾 gl_Position.y = -y（GL y-up -> VK y-down），
 *      相机视口/网格数据与 D3D11 后端逐字节一致；
 *   2) uObjIndex 走 push constant（4B），PerDraw 仍为 std140 UBO（5120B）；
 *   3) v1 的 MVP/Color 走 push constant（80B）；后处理参数 vec4（16B）。
 *
 * 注：内嵌源码行内的 "星斜杠" 序列已消毒为 "星 空格 斜杠"，
 *     不改变语义（仅为避免提前终止本注释块）。
 * ========================================================================= */
